def extract_allowed_identifiers(registry: EvidenceRegistry) -> Tuple[Set[str], Set[str], Set[str]]:
    """Extract all allowed CWEs, CVEs, and OWASP tags from all injected chunks in the registry.

    Scans both structured metadata (cwe, owasp) and chunk content text across ALL injected
    chunks so that no valid identifier present in any injected chunk is falsely flagged.
    """
    allowed_cwe: Set[str] = set()
    allowed_cve: Set[str] = set()
    allowed_owasp: Set[str] = set()

    for c in registry.allowed_cwe:
        match = re.search(r"CWE-(\d+)", c, re.IGNORECASE)
        if match:
            allowed_cwe.add(f"CWE-{match.group(1)}")

    for o in registry.allowed_owasp:
        allowed_owasp.add(o.strip().upper())

    # Scan raw content of all injected chunks for additional mentioned standards
    for chunk in registry.label_to_chunk.values():
        content_cwe = re.findall(r"\bCWE-(\d+)\b", chunk.content, re.IGNORECASE)
        for num in content_cwe:
            allowed_cwe.add(f"CWE-{num}")

        content_cve = re.findall(r"\bCVE-(\d{4}-\d+)\b", chunk.content, re.IGNORECASE)
        for cve_val in content_cve:
            allowed_cve.add(f"CVE-{cve_val.upper()}")

        content_owasp = re.findall(r"\bOWASP\s+([A-Z]\d{2}(?::\d{4})?)\b", chunk.content, re.IGNORECASE)
        for owasp_val in content_owasp:
            allowed_owasp.add(f"OWASP {owasp_val.upper()}")

    return allowed_cwe, allowed_cve, allowed_owasp


class RAGChatPipeline:
    """Orchestrates end-to-end RAG chat processing with deterministic safeguards."""

    def __init__(
        self,
        retriever: Optional[QdrantVectorStore] = None,
        llm_provider: Optional[BaseLLMProvider] = None,
        max_context_chunks: int = DEFAULT_MAX_CONTEXT_CHUNKS,
        max_context_chars: int = DEFAULT_MAX_CONTEXT_CHARS,
    ):
        """Initialize pipeline with optional retriever and provider injection.

        Args:
            retriever: QdrantVectorStore instance. If None, instantiates default store.
            llm_provider: BaseLLMProvider instance. If None, resolved via get_llm_provider().
            max_context_chunks: Maximum evidence chunks injected into prompt.
            max_context_chars: Maximum character budget for prompt evidence blocks.
        """
        self._retriever = retriever
        self._llm_provider = llm_provider
        self.max_context_chunks = max_context_chunks
        self.max_context_chars = max_context_chars

    @property
    def retriever(self) -> QdrantVectorStore:
        """Lazy load or return injected vector retriever."""
        if self._retriever is None:
            self._retriever = get_shared_vector_store()
        return self._retriever

    @property
    def llm_provider(self) -> BaseLLMProvider:
        """Lazy load or return injected LLM provider."""
        if self._llm_provider is None:
            self._llm_provider = get_llm_provider()
        return self._llm_provider

    def process_query(
        self,
        query: str,
        conversation_context: Optional[str] = None,
    ) -> RAGResponse:
        """Execute end-to-end RAG processing with strict attribution and grounding guardrails.

        Args:
            query: Raw user query string.
            conversation_context: Optional text history from prior turns.

        Returns:
            RAGResponse containing answer, citations, grounding metadata, and decomposed latencies.

        Raises:
            ValueError: If query is empty, whitespace-only, or exceeds MAX_QUERY_CHARS.
            LLMProviderError: If the LLM provider fails and cannot be recovered.
        """
        total_t0 = time.perf_counter()

        # 1. Input Validation
        if not query or not query.strip():
            raise ValueError("Query string cannot be empty or whitespace-only.")
        cleaned_query = query.strip()
        if len(cleaned_query) > MAX_QUERY_CHARS:
            raise ValueError(
                f"Query exceeds maximum allowed length of {MAX_QUERY_CHARS} characters (received {len(cleaned_query)})."
            )

        # 2. Linguistic & Intent Analysis (100% Offline)
        intent_result: IntentAnalysisResult = analyze_query_intent(cleaned_query)
        detected_lang = intent_result.language.value
        # Resolve target communication language: default Arabic if Arabic detected, else English
        comm_lang = "ar" if detected_lang == "ar" else "en"
        is_site_specific = intent_result.is_site_specific

        # 3. Vector & Lexical Hybrid Retrieval
        t_ret_0 = time.perf_counter()
        retrieval_result = self.retriever.retrieve(query=cleaned_query)
        t_ret_1 = time.perf_counter()
        retrieval_latency_ms = round((t_ret_1 - t_ret_0) * 1000.0, 2)

        # 4. Deterministic Empty-Retrieval Short-Circuit (Zero LLM Calls)
        if not retrieval_result.matches or len(retrieval_result.matches) == 0:
            refusal_text = STANDARD_REFUSAL_AR if comm_lang == "ar" else STANDARD_REFUSAL_EN
            total_elapsed_ms = round((time.perf_counter() - total_t0) * 1000.0, 2)
            return RAGResponse(
                answer=refusal_text,
                grounded=False,
                grounding_status=GroundingStatus.REFUSED_EMPTY_RETRIEVAL,
                is_site_specific=is_site_specific,
                language=comm_lang,
                retrieved_sources=[],
                cited_sources=[],
                retrieval_latency_ms=retrieval_latency_ms,
                llm_latency_ms=0.0,
                total_latency_ms=total_elapsed_ms,
            )

        # 5. Context Building & Evidence Registry Construction
        context_result: ContextBuildResult = build_rag_context(
            chunks=retrieval_result.matches,
            max_chunks=self.max_context_chunks,
            max_context_chars=self.max_context_chars,
        )

        # If all candidates were malformed, duplicate conflicts, or budget-omitted
        if context_result.injected_count == 0:
            refusal_text = STANDARD_REFUSAL_AR if comm_lang == "ar" else STANDARD_REFUSAL_EN
            total_elapsed_ms = round((time.perf_counter() - total_t0) * 1000.0, 2)
            return RAGResponse(
                answer=refusal_text,
                grounded=False,
                grounding_status=GroundingStatus.REFUSED_EMPTY_RETRIEVAL,
                is_site_specific=is_site_specific,
                language=comm_lang,
                retrieved_sources=[],
                cited_sources=[],
                retrieval_latency_ms=retrieval_latency_ms,
                llm_latency_ms=0.0,
                total_latency_ms=total_elapsed_ms,
            )

        registry = context_result.registry
        retrieved_sources = list(registry.retrieved_sources)

        # 6. Prompt Construction
        system_prompt = build_system_prompt()
        user_prompt = build_user_prompt(
            query=cleaned_query,
            evidence_text=context_result.evidence_text,
            conversation_context=conversation_context,
        )
        messages = [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt},
        ]

        # 7. LLM Generation
        t_llm_0 = time.perf_counter()
        try:
            llm_response: LLMResponse = self.llm_provider.generate(messages)
        except Exception as e:
            # Mask any internal trace or secret, log safely, re-raise safe error
            logger.error("LLM Provider generation failure: %s", type(e).__name__)
            raise LLMProviderError(f"LLM generation failed ({type(e).__name__}). Please check provider configuration.") from None

        t_llm_1 = time.perf_counter()
        llm_latency_ms = round((t_llm_1 - t_llm_0) * 1000.0, 2)
        raw_answer = (llm_response.content or "").strip()

        # 8. Post-Generation Attribution & Grounding Checks

        # Check 0A: Provider Token Truncation Guardrail (finish_reason == "length")
        if llm_response.finish_reason == "length":
            logger.warning("LLM response truncated due to token limit (finish_reason='length'). Suppressing partial answer.")
            truncation_text = TRUNCATION_NOTICE_AR if comm_lang == "ar" else TRUNCATION_NOTICE_EN
            total_elapsed_ms = round((time.perf_counter() - total_t0) * 1000.0, 2)
            return RAGResponse(
                answer=truncation_text,
                grounded=False,
                grounding_status=GroundingStatus.INCOMPLETE_TRUNCATED,
                is_site_specific=is_site_specific,
                language=comm_lang,
                retrieved_sources=retrieved_sources,
                cited_sources=[],
                retrieval_latency_ms=retrieval_latency_ms,
                llm_latency_ms=llm_latency_ms,
                total_latency_ms=total_elapsed_ms,
            )

        # Check 0B: Provider Content Filter Guardrail (finish_reason == "content_filter")
        if llm_response.finish_reason == "content_filter":
            logger.warning("LLM response filtered by provider safety system (finish_reason='content_filter').")
            filter_text = CONTENT_FILTER_NOTICE_AR if comm_lang == "ar" else CONTENT_FILTER_NOTICE_EN
            total_elapsed_ms = round((time.perf_counter() - total_t0) * 1000.0, 2)
            return RAGResponse(
                answer=filter_text,
                grounded=False,
                grounding_status=GroundingStatus.REFUSED_INSUFFICIENT,
                is_site_specific=is_site_specific,
                language=comm_lang,
                retrieved_sources=retrieved_sources,
                cited_sources=[],
                retrieval_latency_ms=retrieval_latency_ms,
                llm_latency_ms=llm_latency_ms,
                total_latency_ms=total_elapsed_ms,
            )

        # Check A: Model emitted standard refusal
        is_refusal = (
            STANDARD_REFUSAL_EN in raw_answer
            or STANDARD_REFUSAL_AR in raw_answer
            or "don't have enough relevant information" in raw_answer.lower()
            or "لا تتوفر لدي معلومات كافية" in raw_answer
        )
        if is_refusal:
            refusal_text = STANDARD_REFUSAL_AR if comm_lang == "ar" else STANDARD_REFUSAL_EN
            total_elapsed_ms = round((time.perf_counter() - total_t0) * 1000.0, 2)
            return RAGResponse(
                answer=refusal_text,
                grounded=False,
                grounding_status=GroundingStatus.REFUSED_INSUFFICIENT,
                is_site_specific=is_site_specific,
                language=comm_lang,
                retrieved_sources=retrieved_sources,
                cited_sources=[],
                retrieval_latency_ms=retrieval_latency_ms,
                llm_latency_ms=llm_latency_ms,
                total_latency_ms=total_elapsed_ms,
            )

        # Extract inline tags like [E1], [ E1 ], [e1], [  e1  ], [E99], [e99]
        cited_labels_raw = re.findall(r"\[\s*[eE](\d+)\s*\]", raw_answer)
        cited_labels = [f"E{num}" for num in cited_labels_raw]

        # If model emitted invalid/unsupported evidence tags
        for label in cited_labels:
            if not registry.is_valid_label(label):
                logger.warning(
                    "Attribution failure: LLM generated unverified evidence tag '[%s]'. Suppressing response.",
                    label,
                )
                failure_text = ATTRIBUTION_FAILURE_AR if comm_lang == "ar" else ATTRIBUTION_FAILURE_EN
                total_elapsed_ms = round((time.perf_counter() - total_t0) * 1000.0, 2)
                return RAGResponse(
                    answer=failure_text,
                    grounded=False,
                    grounding_status=GroundingStatus.ATTRIBUTION_FAILED,
                    is_site_specific=is_site_specific,
                    language=comm_lang,
                    retrieved_sources=retrieved_sources,
                    cited_sources=[],
                    retrieval_latency_ms=retrieval_latency_ms,
                    llm_latency_ms=llm_latency_ms,
                    total_latency_ms=total_elapsed_ms,
                )

        # Check C: Security Identifiers Verification (CWE, CVE, OWASP)
        allowed_cwe, allowed_cve, allowed_owasp = extract_allowed_identifiers(registry)

        # Inspect CWEs in generated narrative
        mentioned_cwes = re.findall(r"\bCWE-(\d+)\b", raw_answer, re.IGNORECASE)
        for num in mentioned_cwes:
            formatted_cwe = f"CWE-{num}"
            if formatted_cwe not in allowed_cwe:
                logger.warning(
                    "Attribution failure: LLM emitted unsupported identifier '%s'. Suppressing response.",
                    formatted_cwe,
                )
                failure_text = ATTRIBUTION_FAILURE_AR if comm_lang == "ar" else ATTRIBUTION_FAILURE_EN
                total_elapsed_ms = round((time.perf_counter() - total_t0) * 1000.0, 2)
                return RAGResponse(
                    answer=failure_text,
                    grounded=False,
                    grounding_status=GroundingStatus.ATTRIBUTION_FAILED,
                    is_site_specific=is_site_specific,
                    language=comm_lang,
                    retrieved_sources=retrieved_sources,
                    cited_sources=[],
                    retrieval_latency_ms=retrieval_latency_ms,
                    llm_latency_ms=llm_latency_ms,
                    total_latency_ms=total_elapsed_ms,
                )

        # Inspect CVEs in generated narrative
        mentioned_cves = re.findall(r"\bCVE-(\d{4}-\d+)\b", raw_answer, re.IGNORECASE)
        for cve_num in mentioned_cves:
            formatted_cve = f"CVE-{cve_num.upper()}"
            if formatted_cve not in allowed_cve:
                logger.warning(
                    "Attribution failure: LLM emitted unsupported identifier '%s'. Suppressing response.",
                    formatted_cve,
                )
                failure_text = ATTRIBUTION_FAILURE_AR if comm_lang == "ar" else ATTRIBUTION_FAILURE_EN
                total_elapsed_ms = round((time.perf_counter() - total_t0) * 1000.0, 2)
                return RAGResponse(
                    answer=failure_text,
                    grounded=False,
                    grounding_status=GroundingStatus.ATTRIBUTION_FAILED,
                    is_site_specific=is_site_specific,
                    language=comm_lang,
                    retrieved_sources=retrieved_sources,
                    cited_sources=[],
                    retrieval_latency_ms=retrieval_latency_ms,
                    llm_latency_ms=llm_latency_ms,
                    total_latency_ms=total_elapsed_ms,
                )

        # Map verified cited labels to SourceCitation objects
        cited_sources: List[SourceCitation] = []
        seen_cited_ids: Set[str] = set()
        for label in cited_labels:
            citation = registry.get_citation_by_label(label)
            if citation and citation.chunk_id not in seen_cited_ids:
                seen_cited_ids.add(citation.chunk_id)
                cited_sources.append(citation)

        # Check D: Site-Specific Target Diagnostic Safeguards
        final_answer = raw_answer
        final_status = GroundingStatus.GROUNDED

        if is_site_specific:
            final_status = GroundingStatus.SITE_SPECIFIC_QUALIFIED
            disclaimer = SITE_SPECIFIC_DISCLAIMER_AR if comm_lang == "ar" else SITE_SPECIFIC_DISCLAIMER_EN

            # Check for unsupported affirmative/negative diagnostic assertions
            diag_patterns = DIAGNOSTIC_CLAIM_PATTERNS_AR if comm_lang == "ar" else DIAGNOSTIC_CLAIM_PATTERNS_EN
            has_unsupported_diagnostic_claim = any(
                re.search(pat, raw_answer, re.IGNORECASE) for pat in diag_patterns
            )

            if has_unsupported_diagnostic_claim:
                # Suppress diagnostic claim and provide strictly educational guidance
                logger.warning(
                    "Diagnostic claim detected on site-specific query. Replacing claim with safe qualification."
                )
                if comm_lang == "ar":
                    educational_guidance = (
                        f"{disclaimer}\n\n"
                        "تحتوي قاعدة المعرفة على مفاهيم أمنية عامة ولكنها لا تستطيع تأكيد ما إذا كان تطبيقك أو نظامك مصاباً بثغرة. "
                        "لتحديد وجود الثغرة، يجب إجراء فحص أمني مصرح به أو تحليل للشفرة البرمجية."
                    )
                else:
                    educational_guidance = (
                        f"{disclaimer}\n\n"
                        "The Knowledge Base contains general vulnerability concepts but cannot verify whether your specific "
                        "application or infrastructure is vulnerable. To determine if this vulnerability exists in your environment, "
                        "perform authorized security testing, automated/manual scanning, or source code analysis."
                    )
                final_answer = educational_guidance
            else:
                # Prepend disclaimer if not already present
                if not raw_answer.startswith(disclaimer):
                    final_answer = f"{disclaimer}\n\n{raw_answer}"

        total_elapsed_ms = round((time.perf_counter() - total_t0) * 1000.0, 2)

        return RAGResponse(
            answer=final_answer,
            grounded=(final_status in (GroundingStatus.GROUNDED, GroundingStatus.SITE_SPECIFIC_QUALIFIED)),
            grounding_status=final_status,
            is_site_specific=is_site_specific,
            language=comm_lang,
            retrieved_sources=retrieved_sources,
            cited_sources=cited_sources,
            retrieval_latency_ms=retrieval_latency_ms,
            llm_latency_ms=llm_latency_ms,
            total_latency_ms=total_elapsed_ms,
        )
